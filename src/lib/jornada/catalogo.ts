export function fornecedorPorId(id: string): Fornecedor | undefined {
  return FORNECEDORES.find((x) => x.id === id)
}

export function fornecedoresDaCategoria(cat: CategoriaId): Fornecedor[] {
  return FORNECEDORES.filter((x) => x.categorias.includes(cat))
}

export const NAO_INFORMADO = 'Não informado — confirmar com o fornecedor'

export function moeda(v: number | null): string {
  if (v === null) return NAO_INFORMADO
  if (v === 0) return 'R$ 0 (sem custo)'
  return `R$ ${v.toLocaleString('pt-BR')}`
}
